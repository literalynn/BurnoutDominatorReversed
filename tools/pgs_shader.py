"""Compiles ps2xRuntime/src/lib/gs/shaders/pgs_sample_circuit.frag into pgs_sample_circuit.spv.h.

usage: python tools/pgs_shader.py --glslang <glslangValidator> --pgs <paraLLEl-GS checkout>

glslangValidator builds from the checkout's Granite/third_party/glslang (target
glslang-standalone). The header is committed, so building the game does not need it.
"""
import argparse
import pathlib
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADERS = ROOT / "ps2xRuntime" / "src" / "lib" / "gs" / "shaders"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--glslang", required=True)
    parser.add_argument("--pgs", required=True, type=pathlib.Path)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as scratch:
        spv = pathlib.Path(scratch) / "out.spv"
        subprocess.run([args.glslang, "-V", "--target-env", "vulkan1.1",
                        "-I" + str(args.pgs / "gs" / "shaders"),
                        "-I" + str(args.pgs / "Granite" / "assets" / "shaders" / "inc"),
                        "-DPROMOTED=0", str(SHADERS / "pgs_sample_circuit.frag"), "-o", str(spv)], check=True)
        data = spv.read_bytes()
    assert len(data) % 4 == 0 and data[:4] == bytes.fromhex("03022307"), "not SPIR-V"
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    lines = ["// Generated by tools/pgs_shader.py from pgs_sample_circuit.frag (PROMOTED=0). Do not edit.",
             "// SPDX-License-Identifier: LGPL-3.0+ (derived from paraLLEl-GS)",
             "#pragma once",
             "#include <stdint.h>",
             "static const uint32_t pgs_sample_circuit_spirv[] = {"]
    for i in range(0, len(words), 8):
        lines.append("\t" + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",")
    lines.append("};")
    (SHADERS / "pgs_sample_circuit.spv.h").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("%d words" % len(words))


if __name__ == "__main__":
    main()
