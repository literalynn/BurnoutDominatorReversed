void EeScheduler::reset(uint8_t *rdram, const R5900Context &mainContext)
{
    m_executorThread = std::this_thread::get_id();
    m_rdram = rdram;
    m_readyQueues = {};
    m_threads.clear();
    m_cachedThreadId = 0;
    m_cachedThread = nullptr;
    m_semaphores.clear();
    m_eventFlags.clear();
    m_alarms.clear();
    m_intcHandlers.clear();
    m_dmacHandlers.clear();
    m_nextThreadId = kFirstThreadId;
    m_nextInvocationThreadId = -1;
    m_nextSemaphoreId = 1;
    m_nextEventFlagId = 1;
    m_nextAlarmId = 1;
    m_nextIntcHandlerId = 1;
    m_nextDmacHandlerId = 1;
    m_intcHeadOrder = 0;
    m_intcTailOrder = 1000;
    m_dmacHeadOrder = 0;
    m_dmacTailOrder = 1000;
    m_enabledIntcMask = 0xFFFFFFFFu;
    m_enabledDmacMask = 0xFFFFFFFFu;
    m_currentThreadId = 0;
    m_rescheduleRequested = false;
    m_timeSliceExpired = false;
    m_insideInterrupt = false;
    m_pendingEeTimerInterrupts = 0u;
    m_eeCycle = 0u;
    g_countLagCycles = 0u;
    m_deviceCycleDebt = 0u;
    m_sliceEndCycle = kDefaultTimeSliceCycles;
    m_stopRequested.store(false, std::memory_order_release);
    m_checkpointPending.store(false, std::memory_order_release);
    m_debugPublishCountdown = 0u;
    {
        std::lock_guard lock(m_eventMutex);
        m_events.clear();
        m_deadlines.clear();
        m_pendingInvocations.clear();
    }
    m_eventSequence = 0;
    m_invocationSequence = 0;
    m_vsyncTick = 0;
    m_vsyncFlagAddress = 0;
    m_vsyncTickAddress = 0;
    m_gsVSyncCallback = 0;
    m_gsVSyncCallbackGp = 0;
    m_gsVSyncCallbackSp = 0;
    m_runtime.memory().gs().vsyncTick.store(0u, std::memory_order_release);
    m_runtime.memory().resetEeTimers();

    GuestThread main{};
    main.id = kMainThreadId;
    main.context = mainContext;
    main.entry = mainContext.pc;
    // $sp is live execution state, not the stable initial stack descriptor
    // returned by ReferThreadStatus. SetupThread records that metadata.
    main.stack = 0u;
    main.gp = getRegU32(&mainContext, 28);
    main.initialPriority = 0;
    main.currentPriority = 0;
    main.status = EeThreadStatus::Ready;
    m_threads.emplace(main.id, std::move(main));
    m_readyQueues[0].push_back(kMainThreadId);
    scheduleEvent(m_eeCycle + vblankPeriodCycles(false),
                  std::chrono::steady_clock::now() + vblankPeriod(false),
                  EeEvent{EeEventType::VBlankStart, 0, 0});
    publishSnapshot();
}

void EeScheduler::run()
{
    assertExecutor();
    ps2_wait_stats::t_gameThread = true;
    // The EE FPU and VU0 in macro mode round toward zero (as PCSX2 does by default); games
    // rely on it, Burnout's VU0 cosine rounds with 1.5 * 2^23 and jumped at a half turn.
    // Restored on the way out: the thread may run other host code afterwards (the tests do).
    struct RoundingGuard
    {
        int previous = std::fegetround();
        ~RoundingGuard() { std::fesetround(previous); }
    } roundingGuard;
    std::fesetround(FE_TOWARDZERO);
    m_running.store(true, std::memory_order_release);

    while (!m_stopRequested.load(std::memory_order_acquire))
    {
        // Paused between slices, where a state save also stops; the VBlank schedule
        // restarts from the clock afterwards (at most one period behind).
        while (ps2x::emulationPaused() && !m_stopRequested.load(std::memory_order_acquire))
            std::this_thread::sleep_for(std::chrono::milliseconds(5));
        if (m_runtime.m_stateRequestPending.load(std::memory_order_acquire))
        {
            // The native stack is unwound here: all guest state is in thread contexts and memory.
            m_runtime.serviceStateRequest();
            if (m_stopRequested.load(std::memory_order_acquire))
            {
                break;
            }
        }

        processPendingEvents();
        if (m_stopRequested.load(std::memory_order_acquire))
        {
            break;
        }

        if (m_currentThreadId == 0)
        {
            GuestThread *next = selectReady();
            if (!next && m_pendingInvocations.empty())
            {
                copyMainContextToRuntime();
                publishIdleDebugContext();
                publishSnapshot();
                waitForEvent();
                continue;
            }
            if (next)
            {
                makeRunning(*next);
            }
            else
            {
                GuestThread *owner = &acquireInvocationThread();
                GuestInvocation invocation = std::move(m_pendingInvocations.front());
                m_pendingInvocations.pop_front();
                owner->status = EeThreadStatus::Running;
                m_currentThreadId = owner->id;
                renewTimeSlice();
                if (getRegU32(&invocation.context, 29) == 0u)
                {
                    SET_GPR_U32(&invocation.context, 29, invocationStackTop());
                }
                owner->invocations.push_back(std::move(invocation));
            }
        }

        GuestThread *running = currentThread();
        assert(running != nullptr);
        if (running->resumeCompletion)
        {
            auto completion = std::move(running->resumeCompletion);
            running->resumeCompletion = {};
            try
            {
                completion(running->activeContext());
            }
            catch (const EeDispatcherTransfer &)
            {
            }
            if (m_currentThreadId == 0)
            {
                continue;
            }
        }
        R5900Context &context = running->activeContext();
        if (m_debugPublishCountdown == 0u)
        {
            copyMainContextToRuntime();
            publishSnapshot();
            m_debugPublishCountdown = kDebugPublishDispatchInterval - 1u;
        }
        else
        {
            --m_debugPublishCountdown;
        }

        publishDebugContext(context);

        if (context.pc == 0u)
        {
            if (!running->invocations.empty())
            {
                GuestInvocation completed = std::move(running->invocations.back());
                running->invocations.pop_back();
                if (completed.onComplete)
                {
                    try
                    {
                        completed.onComplete(completed.context, running->activeContext());
                    }
                    catch (const EeDispatcherTransfer &)
                    {
                    }
                }
                continue;
            }
            makeDormant(*running);
            m_currentThreadId = 0;
            copyMainContextToRuntime();
            publishIdleDebugContext();
            publishSnapshot();
            continue;
        }

        // Queued handlers (INTC, DMAC, alarms, VSync and SIF callbacks) run in
        // interrupt context on the EE: they wait while the thread has EIE
        // cleared (di ... ei).
        if (!m_pendingInvocations.empty() && running->invocations.empty() && (context.cop0_status & 0x10000u) != 0u)
        {
            GuestInvocation invocation = std::move(m_pendingInvocations.front());
            m_pendingInvocations.pop_front();
            if (getRegU32(&invocation.context, 29) == 0u)
            {
                SET_GPR_U32(&invocation.context, 29, invocationStackTop());
            }
            running->invocations.push_back(std::move(invocation));
            continue;
        }

        if (!hasGeneratedFunction(context.pc))
        {
            if (!running->invocations.empty())
            {
                context.pc = 0u;
            }
            else
            {
                if (dispatchHistoryEnabled())
                {
                    printDispatchHistory();
                }
                m_runtime.reportMissingFunction(m_rdram,
                                                &context,
                                                context.pc,
                                                context.pc,
                                                PS2Runtime::GuestBranchKind::DirectJump,
                                                "EE scheduler");
                makeDormant(*running);
                m_currentThreadId = 0;
            }
            continue;
        }
        PS2Runtime::RecompiledFunction function = m_runtime.lookupFunction(context.pc);

        uint32_t dispatchCycles = kGuestDispatchCycles;
        if (const ps2x::IdleCheck idle = ps2x::idleLoopAt(context.pc); idle && idle(m_rdram, context))
        {
            // A declared polling loop: skip to the next event, within one device batch.
            const uint64_t next = m_nextDeadlineCycle.load(std::memory_order_acquire);
            const uint64_t untilEvent = next == 0u ? kDeviceBatchCycles : next > m_eeCycle ? next - m_eeCycle : 0u;
            dispatchCycles = static_cast<uint32_t>(
                std::clamp<uint64_t>(untilEvent, kGuestDispatchCycles, kDeviceBatchCycles));
        }
        if (checkpointDue(dispatchCycles))
        {
            continue;
        }

        try
        {
            m_insideInterrupt = !running->invocations.empty() && running->invocations.back().kind == GuestInvocationKind::Interrupt;
            m_guestExecuting.store(true, std::memory_order_release);
            const uint32_t dispatchedPc = context.pc;
            ps2_ee_unwind::g_returningToScheduler = false;
            if (dispatchHistoryEnabled())
            {
                g_dispatchRecords[g_dispatchNext++ % kDispatchHistory] =
                    DispatchRecord{m_currentThreadId, context.pc, getRegU32(&context, 29), getRegU32(&context, 31)};
            }
            function(m_rdram, &context, &m_runtime);
            m_guestExecuting.store(false, std::memory_order_release);
            m_insideInterrupt = false;
            // A runtime handler bound over a library function does the whole call and leaves pc
            // on it: from generated code, dispatchGuestBranch returns to the caller. Run from here
            // (a checkpoint fell on the call, or a jump went to it), it returns to ra, or it would
            // run again forever: Burnout's pad RPC 0x80001302, 550,000 times a second.
            if (context.pc == dispatchedPc && !ps2_ee_unwind::g_returningToScheduler &&
                ps2_game_overrides::isBoundHandler(dispatchedPc))
            {
                context.pc = getRegU32(&context, 31);
            }
            if (wordWatch().enabled)
            {
                checkWordWatch(m_rdram, dispatchedPc, context);
            }
        }
        catch (const EeDispatcherTransfer &)
        {
            m_guestExecuting.store(false, std::memory_order_release);
            m_insideInterrupt = false;
        }
        catch (...)
        {
            m_guestExecuting.store(false, std::memory_order_release);
            m_running.store(false, std::memory_order_release);
            publishSnapshot();
            throw;
        }

        processPendingEvents();
        if (m_rescheduleRequested && m_currentThreadId != 0)
        {
            GuestThread *preempted = currentThread();
            assert(preempted != nullptr);
            enqueueReady(*preempted, !m_timeSliceExpired);
            m_currentThreadId = 0;
            m_rescheduleRequested = false;
            m_timeSliceExpired = false;
        }
    }

    m_guestExecuting.store(false, std::memory_order_release);
    m_running.store(false, std::memory_order_release);
    copyMainContextToRuntime();
    publishSnapshot();
}

void EeScheduler::requestStop()
{
    m_stopRequested.store(true, std::memory_order_release);
    m_checkpointPending.store(true, std::memory_order_release);
    m_eventCv.notify_all();
}

void EeScheduler::postEvent(EeEvent event)
{
    if (event.type == EeEventType::Stop)
    {
        requestStop();
        return;
    }

    {
        std::lock_guard lock(m_eventMutex);
        m_events.push_back(event);
        m_checkpointPending.store(true, std::memory_order_release);
    }
    m_eventCv.notify_one();
}

bool EeScheduler::hasGeneratedFunction(uint32_t address) noexcept
{
    // Same test as PS2Runtime::hasFunction, inlined into the dispatch loop.
    if ((address & 3u) != 0u || address < g_ps2RecompiledFunctionTableBase || address >= g_ps2RecompiledFunctionTableEnd)
    {
        return false;
    }
    const uint32_t slot = (address - g_ps2RecompiledFunctionTableBase) >> 2u;
    return slot < g_ps2RecompiledFunctionTableSlotCount && g_ps2RecompiledFunctionTable[slot] != nullptr;
}

namespace
{
    // BDR_EE_CYCLE_SCALE=P charges P% of the cycles the generated code reports
    // at its checkpoints (default 100). The recompiler charges a fixed 32
    // cycles per backward branch whatever the loop length, so this is an
    // experiment knob for EE timing, like an emulator's EE cycle rate.
    uint32_t eeCycleScalePercent()
    {
        static const uint32_t percent = []
        {
            const char *value = std::getenv("BDR_EE_CYCLE_SCALE");
            const long parsed = value ? std::strtol(value, nullptr, 10) : 100;
            return static_cast<uint32_t>(std::clamp<long>(parsed, 1, 1000));
        }();
        return percent;
    }
}

bool EeScheduler::checkpointDue(uint32_t cycles) noexcept
{
    const uint32_t percent = eeCycleScalePercent();
    accountCycles(percent == 100u ? cycles : std::max<uint32_t>(1u, static_cast<uint32_t>((static_cast<uint64_t>(cycles) * percent) / 100u)));

    if (m_checkpointPending.load(std::memory_order_acquire) ||
        m_stopRequested.load(std::memory_order_acquire))
    {
        ps2_ee_unwind::g_returningToScheduler = true;
        return true;
    }

    const uint64_t nextEventCycle = m_nextDeadlineCycle.load(std::memory_order_acquire);
    if (nextEventCycle != 0u && m_eeCycle >= nextEventCycle)
    {
        m_checkpointPending.store(true, std::memory_order_release);
        ps2_ee_unwind::g_returningToScheduler = true;
        return true;
    }

    if (m_eeCycle < m_sliceEndCycle)
    {
        return false;
    }

    const GuestThread *running = currentThread();
    if (running != nullptr && hasReadyAtOrAbovePriority(running->currentPriority))
    {
        m_rescheduleRequested = true;
        m_timeSliceExpired = true;
        ps2_ee_unwind::g_returningToScheduler = true;
        return true;
    }

    renewTimeSlice();
    return false;
}

