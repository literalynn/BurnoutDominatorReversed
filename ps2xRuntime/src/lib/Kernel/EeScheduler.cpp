    constexpr uint32_t kDebugPublishDispatchInterval = 4096u;

    constexpr uint64_t microsecondsToEeCycles(uint64_t microseconds)
    {
        return (microseconds * EeScheduler::kEeClockHz + 999999ull) / 1000000ull;
    }

    std::chrono::nanoseconds eeCyclesToHostDuration(uint64_t cycles)
    {
        constexpr uint64_t kNanosecondsPerSecond = 1000000000ull;
        const uint64_t wholeSeconds = cycles / EeScheduler::kEeClockHz;
        const uint64_t remainingCycles = cycles % EeScheduler::kEeClockHz;
        const uint64_t remainingNanoseconds = (remainingCycles * kNanosecondsPerSecond + EeScheduler::kEeClockHz - 1u) / EeScheduler::kEeClockHz;
        return std::chrono::seconds(wholeSeconds) + std::chrono::nanoseconds(remainingNanoseconds);
    }

    constexpr uint64_t kVBlankPeriodCycles = microsecondsToEeCycles(16667u);

    // With keep_speed, COP0 Count runs at the EE clock, plus the host time by which
    // emulated time fell behind real time: a console would have spent that time
    // drawing. A game that times its frames with Count (Burnout's governor at
    // 0x1E6728) then runs more simulation steps per drawn frame and keeps its
    // speed when the host cannot keep up. Only the lag the VBlank schedule drops
    // counts (it may trail real time by one period), at most two periods per
    // VBlank and none after a pause or a long stall, where the game waits instead
    // of jumping ahead. (Adding the game thread's waits for the GS worker counted
    // time twice when the wait ended before the VBlank: the race ran up to 60%
    // fast.) Replays (BDR_DETERMINISTIC) count EE cycles only. Without keep_speed
    // Count is left alone (FINDINGS.md E019).
    uint64_t g_countLagCycles = 0u;
    bool g_countRuns = false;
    constexpr auto kCountStallLimit = std::chrono::milliseconds(250);

    uint64_t hostDurationToEeCycles(std::chrono::nanoseconds duration)
    {
        return static_cast<uint64_t>(duration.count()) * EeScheduler::kEeClockHz / 1000000000ull;
    }
    constexpr uint64_t kPalVBlankPeriodCycles = microsecondsToEeCycles(20000u);

    // VBlanks a second of a game run faster than the console (vblank_rate.h), 0 for the console's.
    std::atomic<uint32_t> g_vblankRate{0u};

    std::chrono::nanoseconds vblankPeriod(bool pal)
    {
        const uint32_t rate = g_vblankRate.load(std::memory_order_relaxed);
        if (rate != 0u)
            return std::chrono::nanoseconds(1000000000ull / rate);
        return pal ? kPalVBlankPeriod : kVBlankPeriod;
    }

    uint64_t vblankPeriodCycles(bool pal)
    {
        const uint32_t rate = g_vblankRate.load(std::memory_order_relaxed);
        if (rate != 0u)
            return EeScheduler::kEeClockHz / rate;
        return pal ? kPalVBlankPeriodCycles : kVBlankPeriodCycles;
    }
    constexpr uint64_t kVBlankDurationCycles = microsecondsToEeCycles(500u);
    constexpr uint64_t kAlarmTickCycles = microsecondsToEeCycles(kAlarmTickMicroseconds);

    template <typename Map>
    int allocatePositiveId(int &nextId, const Map &objects)
    {
        const int first = std::max(1, nextId);
        int candidate = first;
        do
        {
            if (!objects.contains(candidate))
            {
                nextId = (candidate == std::numeric_limits<int>::max()) ? 1 : candidate + 1;
                return candidate;
            }
            candidate = (candidate == std::numeric_limits<int>::max()) ? 1 : candidate + 1;
        } while (candidate != first);
        return 0;
    }
